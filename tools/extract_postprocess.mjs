import fs from 'node:fs';
import path from 'node:path';
import {NativeSceneWriter} from './native_scene_writer.mjs';
globalThis.location={search:'?route=main',pathname:'/'};
const root=path.resolve(import.meta.dirname,'..');
const look=(await import('./.reference_runtime/Da-Ct4tY.js')).__port;
const writer=new NativeSceneWriter(root);
const encode=shader=>({vertex:shader.vertexShader,fragment:shader.fragmentShader,defines:shader.defines??{},uniforms:Object.fromEntries(Object.entries(shader.uniforms).map(([k,v])=>[k,writer.uniform(v.value)]))});
const bloom=new look.Ac(new look.V(256,256),.5,.55,.8);
const output={grade:encode(look.Pc),final:encode(look.Fc),copy:encode(look.wc),high:encode(bloom.materialHighPassFilter),blur:bloom.separableBlurMaterials.map(encode),composite:encode(bloom.compositeMaterial),guard:encode(new look.Lc(new look.C(),{},256,256,false).quad.material)};
fs.writeFileSync(path.join(root,'go_home_mobile/assets/world/postprocess.json'),JSON.stringify(output));
console.log('Extracted original grade, final, HDR guard and 5 bloom levels.');
